"""
Unified CoT Generation + Hidden State Extraction + Trajectory Extraction Pipeline

Extracts hidden states faithfully to the paper methodology:
- h(ℓ)_t(Step k)−1: Hidden state at token PRECEDING each "Step" marker (generated by model)
- h(ℓ)_t(term)−1: Hidden state at token PRECEDING final answer marker "####" (generated by model)

HOW IT WORKS:
1. Prompt INSTRUCTS the model to use "Step [step_number]: " format and "#### [answer]"
2. Model GENERATES text following this format (e.g., "Step 1: ...\nStep 2: ...\n#### answer")
3. Script DETECTS token ID 8468 ("Step") in the model's output via token sequence search
4. Script EXTRACTS hidden states at position-1 (the token before each marker)

EXPECTED OUTPUT FORMAT (from model):
    Step 1: [reasoning text]
    Step 2: [reasoning text]
    Step 3: [reasoning text]
    #### [final answer]

Handles three dataset types:
1. ReliableMath (unsol.parquet) - with solvability tags
2. ReliableMath (solve.parquet) - with solvability tags
3. GSM8K / AIME - no solvability tags

Features:
- Generates CoT with prompt that instructs "Step X:" format (matches repo template)
- Detects Step markers in model's generated token sequence (token ID 8468)
- Extracts hidden states at precise positions: preceding each marker
- Saves trajectory snapshots: metadata (JSON) + hidden states (NPZ)

NOTE: Token ID 8468 is "Step" in Llama tokenizer. The script searches for this
      token in the generated sequence. If model doesn't generate this format,
      no trajectory points will be extracted.
"""

import re
import json
import argparse
import logging
from pathlib import Path
from typing import Dict, List, Tuple, Any, Optional
from dataclasses import dataclass, asdict
from collections import defaultdict

import numpy as np
import torch
from datasets import load_dataset
from tqdm import tqdm
from transformers import AutoTokenizer, AutoModelForCausalLM

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)


# -------------------------
# Constants
# -------------------------

STEP_TOKEN_ID = 8468  # Token ID for "Step" (with capital S)
STEP_MARKER = "Step"
FINAL_ANSWER_MARKER = "####"


# -------------------------
# Data structures
# -------------------------

@dataclass
class TrajectoryPoint:
    """Single point in the reasoning trajectory"""
    point_type: str  # "step" or "final_answer"
    step_num: Optional[int]  # Which step (0-indexed) for "step" type
    token_position: int  # Position in full sequence (absolute)
    hidden_pos: int  # Position from which hidden state was extracted (token_position - 1)
    marker_text: str  # Text of the marker ("Step 1", "####", etc.)


@dataclass
class Section:
    """Thinking or response section"""
    name: str  # "thinking" or "response"
    text: str
    start_token: int
    end_token: int


@dataclass
class Example:
    """Single example with generated CoT and trajectory"""
    example_idx: int
    question: str
    answer: str
    full_generated_text: str
    generated_token_ids: List[int]
    thinking_section: Optional[Section]
    response_section: Optional[Section]
    trajectory_points: List[TrajectoryPoint]
    ground_truth: Optional[str]
    is_solvable: Optional[bool]
    per_layer_hidden_states: Dict[int, Dict[int, torch.Tensor]]  # {layer: {hidden_pos: tensor}}


